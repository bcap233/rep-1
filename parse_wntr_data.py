import pandas as pd
from datetime import datetime

# Parse the raw data
dividends = {}
trades = {}

for line in raw_data.split("\n"):
    line = line.strip()
    if not line:
        continue

    parts = line.split("\t")
    date_str = parts[0].strip()

    # Parse date
    try:
        date = datetime.strptime(date_str, "%b %d, %Y")
    except ValueError:
        continue

    date_key = date.strftime("%Y-%m-%d")

    # Check if this is a dividend line
    if len(parts) == 2 and "Dividend" in parts[1]:
        div_amount = float(parts[1].replace("Dividend", "").strip())
        dividends[date_key] = div_amount
    elif len(parts) >= 5:
        # Trading data: Open, High, Low, Close, ...
        close = float(parts[4].strip())
        trades[date_key] = close

# Build CSV
rows = []
for date_key in sorted(trades.keys(), reverse=True):
    close = trades[date_key]
    div = dividends.get(date_key, 0)
    rows.append(f"{date_key},{close},{div},1")

csv_content = "Date,Close,Dividend,Split\n" + "\n".join(rows) + "\n"

with open("wntr_data_with_dividends.csv", "w") as f:
    f.write(csv_content)

print(f"Written {len(rows)} trading days")
print(f"Found {len(dividends)} dividend payments")
print(f"Total dividends: ${sum(dividends.values()):.3f}")

# Verify
df = pd.read_csv("wntr_data_with_dividends.csv", parse_dates=["Date"], index_col="Date")
df = df.sort_index()
print(f"\nDate range: {df.index[0].date()} to {df.index[-1].date()}")
print(f"Price range: ${df['Close'].min():.2f} to ${df['Close'].max():.2f}")
print(f"\nDividend dates:")
for date, row in df[df['Dividend'] > 0].iterrows():
    print(f"  {date.date()}: ${row['Dividend']:.3f}")
